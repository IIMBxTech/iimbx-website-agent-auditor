        // Track the user's selected variant index for each page. Default to 0.
        const variantSelections = {};

        // Map expected hrefs to db keys for automatic routing
        const hrefMap = {
            "homepage": "homepage",
            "contact": "contact",
            "about": "about",
            "blog": "blog",
            "services": "services",
            "productpage": "productpage",
            "catalog": "catalog",
            "parts": "parts",
            "media": "media"
        };

        // True Journey State
        let journeySteps = []; // array of { pageId, variantIndex }
        let currentStepIndex = 0;
        let isJourneyMode = false;

        let currentActiveId = null;
        let viewMode = 'preview'; // 'preview' or 'code'

        // Initialize Dashboard
        function init() {
            const pageList = document.getElementById('pageList');
            pageList.innerHTML = '';
            
            // Load saved variant selections
            let savedSelections = {};
            try {
                const saved = localStorage.getItem('krishtekVariantSelections');
                if (saved) savedSelections = JSON.parse(saved);
            } catch(e) {}

            // 1. Group DB items by category
            const categories = {};
            for (const [id, data] of Object.entries(db)) {
                const cat = data.category || "Frontend Pages";
                if (!categories[cat]) categories[cat] = {};
                categories[cat][id] = data;
            }

            // 2. Render foldable categories
            for (const [catName, items] of Object.entries(categories)) {
                const catHeader = document.createElement('div');
                catHeader.className = 'category-header';
                catHeader.innerHTML = `<span>📁 ${catName}</span> <span class="toggle-icon">▼</span>`;
                
                const catContent = document.createElement('div');
                catContent.className = 'category-content';
                
                catHeader.onclick = () => {
                    const isHidden = catContent.style.display === 'none';
                    catContent.style.display = isHidden ? 'flex' : 'none';
                    catHeader.querySelector('.toggle-icon').innerText = isHidden ? '▼' : '▶';
                };

                // Add journey to frontend pages
                if (catName === "Frontend Pages") {
                    const journeyTile = document.createElement('div');
                    journeyTile.className = 'page-tile';
                    journeyTile.id = 'tile-journey';
                    journeyTile.onclick = loadJourneyBuilder;
                    journeyTile.innerHTML = `<div class="page-title">User Journey Flow</div><div class="page-meta">Build & preview site flows</div>`;
                    catContent.appendChild(journeyTile);
                }
            
                for (const [id, data] of Object.entries(items)) {
                    let savedIdx = savedSelections[id] !== undefined ? savedSelections[id] : 0;
                    if (savedIdx >= data.variants.length) {
                        savedIdx = 0; // fallback if variants changed
                    }
                    variantSelections[id] = savedIdx;

                    const tile = document.createElement('div');
                    tile.className = 'page-tile';
                    tile.id = `tile-${id}`;
                    tile.onclick = () => loadPage(id);
                    tile.innerHTML = `
                        <div class="page-title">${data.title}</div>
                        <div class="page-meta">${data.desc} • ${data.variants.length} Variants</div>
                    `;
                    catContent.appendChild(tile);
                }
                
                pageList.appendChild(catHeader);
                pageList.appendChild(catContent);
            }

            // Load first page by default
            if (Object.keys(db).length > 0) {
                loadPage(Object.keys(db)[0]);
            }
        }

        function loadPage(id, fromJourney = false) {
            // Update Active State
            if (currentActiveId && currentActiveId !== 'journey') {
                document.getElementById(`tile-${currentActiveId}`).classList.remove('active');
            }
            if (!fromJourney) {
                document.getElementById('tile-journey').classList.remove('active');
                document.getElementById('journeyBuilder').style.display = 'none';
                document.getElementById('journeyPlayerBar').style.display = 'none';
                document.getElementById('previewFrame').style.display = 'block';
                isJourneyMode = false;
            }
            if (document.getElementById(`tile-${id}`)) {
                document.getElementById(`tile-${id}`).classList.add('active');
            }
            currentActiveId = id;

            const data = db[id];
            document.getElementById('currentTitle').innerText = data.title;

            // Populate Variant Dropdown
            const select = document.getElementById('variantSelect');
            select.innerHTML = '';
            data.variants.forEach((v, index) => {
                const opt = document.createElement('option');
                opt.value = index;
                opt.innerText = v.name;
                if (index === variantSelections[id]) opt.selected = true;
                select.appendChild(opt);
            });

            // Handle Variant Change
            select.onchange = (e) => {
                variantSelections[id] = parseInt(e.target.value);
                localStorage.setItem('krishtekVariantSelections', JSON.stringify(variantSelections));
                if (isJourneyMode) {
                    journeySteps[currentStepIndex].variantIndex = variantSelections[id];
                    saveJourneyFlow();
                }
                renderActiveVariant(data.variants[variantSelections[id]].file);
            };
            
            // Render first variant
            renderActiveVariant(data.variants[variantSelections[id]].file);
        }

        function saveJourneyFlow() {
            localStorage.setItem('krishtekJourneyFlow', JSON.stringify(journeySteps));
        }

        function loadJourneyBuilder() {
            if (currentActiveId && currentActiveId !== 'journey') {
                document.getElementById(`tile-${currentActiveId}`).classList.remove('active');
            }
            document.getElementById('tile-journey').classList.add('active');
            currentActiveId = 'journey';

            document.getElementById('currentTitle').innerText = 'Journey Flow Builder';
            document.getElementById('variantSelect').innerHTML = '<option>Flow Settings</option>';
            
            document.getElementById('previewFrame').style.display = 'none';
            document.getElementById('codeView').style.display = 'none';
            document.getElementById('journeyPlayerBar').style.display = 'none';
            document.getElementById('journeyBuilder').style.display = 'block';
            isJourneyMode = false;

            // default steps if empty or load from storage
            const saved = localStorage.getItem('krishtekJourneyFlow');
            if (saved) {
                try {
                    journeySteps = JSON.parse(saved);
                } catch(e) {}
            }
            
            if (journeySteps.length === 0) {
                journeySteps.push({ pageId: 'homepage', variantIndex: 0 });
                journeySteps.push({ pageId: 'contact', variantIndex: 0 });
                saveJourneyFlow();
            }

            renderJourneySteps();
        }

        function renderJourneySteps() {
            const container = document.getElementById('journeySettings');
            container.innerHTML = '';

            journeySteps.forEach((step, index) => {
                const row = document.createElement('div');
                row.className = 'step-row';

                const num = document.createElement('div');
                num.style.fontWeight = 'bold';
                num.style.width = '60px';
                num.innerText = `Step ${index + 1}`;
                row.appendChild(num);

                // Page Dropdown
                const pageSel = document.createElement('select');
                pageSel.className = 'variant-select';
                pageSel.style.flex = '1';
                Object.entries(db).forEach(([id, data]) => {
                    const opt = document.createElement('option');
                    opt.value = id;
                    opt.innerText = data.title;
                    if (id === step.pageId) opt.selected = true;
                    pageSel.appendChild(opt);
                });

                // Variant Dropdown
                const varSel = document.createElement('select');
                varSel.className = 'variant-select';
                varSel.style.flex = '1';
                const populateVariants = (pageId) => {
                    varSel.innerHTML = '';
                    db[pageId].variants.forEach((v, vIdx) => {
                        const opt = document.createElement('option');
                        opt.value = vIdx;
                        opt.innerText = v.name;
                        if (vIdx === step.variantIndex) opt.selected = true;
                        varSel.appendChild(opt);
                    });
                };
                populateVariants(step.pageId);

                pageSel.onchange = (e) => {
                    step.pageId = e.target.value;
                    step.variantIndex = 0; // reset
                    populateVariants(step.pageId);
                    saveJourneyFlow();
                };
                varSel.onchange = (e) => {
                    step.variantIndex = parseInt(e.target.value);
                    saveJourneyFlow();
                };

                row.appendChild(pageSel);
                row.appendChild(varSel);

                // Controls
                const upBtn = document.createElement('button');
                upBtn.innerHTML = '&#8593;';
                upBtn.title = 'Move Up';
                upBtn.onclick = () => moveStep(index, -1);
                upBtn.disabled = index === 0;

                const downBtn = document.createElement('button');
                downBtn.innerHTML = '&#8595;';
                downBtn.title = 'Move Down';
                downBtn.onclick = () => moveStep(index, 1);
                downBtn.disabled = index === journeySteps.length - 1;

                const rmBtn = document.createElement('button');
                rmBtn.innerText = '✕';
                rmBtn.title = 'Remove Step';
                rmBtn.onclick = () => {
                    journeySteps.splice(index, 1);
                    saveJourneyFlow();
                    renderJourneySteps();
                };

                row.appendChild(upBtn);
                row.appendChild(downBtn);
                row.appendChild(rmBtn);

                container.appendChild(row);
            });
        }

        function addJourneyStep() {
            const firstPageId = Object.keys(db)[0];
            journeySteps.push({ pageId: firstPageId, variantIndex: 0 });
            saveJourneyFlow();
            renderJourneySteps();
        }

        function moveStep(index, direction) {
            const newIndex = index + direction;
            if (newIndex >= 0 && newIndex < journeySteps.length) {
                const temp = journeySteps[index];
                journeySteps[index] = journeySteps[newIndex];
                journeySteps[newIndex] = temp;
                saveJourneyFlow();
                renderJourneySteps();
            }
        }

        function startJourney() {
            if (journeySteps.length === 0) return alert('Please add at least one step.');
            isJourneyMode = true;
            currentStepIndex = 0;
            
            document.getElementById('journeyBuilder').style.display = 'none';
            document.getElementById('previewFrame').style.display = 'block';
            document.getElementById('journeyPlayerBar').style.display = 'flex';
            
            playCurrentStep();
        }

        function playCurrentStep() {
            const step = journeySteps[currentStepIndex];
            const data = db[step.pageId];
            
            document.getElementById('journeyProgress').innerText = `Step ${currentStepIndex + 1} of ${journeySteps.length}: ${data.title}`;
            
            // Sync variant selections
            variantSelections[step.pageId] = step.variantIndex;
            localStorage.setItem('krishtekVariantSelections', JSON.stringify(variantSelections));
            loadPage(step.pageId, true); // true = keep journey mode active
        }

        function nextJourneyStep() {
            if (currentStepIndex < journeySteps.length - 1) {
                currentStepIndex++;
                playCurrentStep();
            }
        }

        function prevJourneyStep() {
            if (currentStepIndex > 0) {
                currentStepIndex--;
                playCurrentStep();
            }
        }

        function exitJourney() {
            isJourneyMode = false;
            document.getElementById('journeyPlayerBar').style.display = 'none';
            loadJourneyBuilder();
        }

        async function renderActiveVariant(filePath) {
            // 1. Update Preview iframe
            document.getElementById('previewFrame').src = filePath;

            // 2. Fetch code for the code viewer
            try {
                const response = await fetch(filePath);
                if (!response.ok) throw new Error('File not found locally yet');
                const code = await response.text();
                // Escape HTML tags for display
                document.getElementById('codeView').innerHTML = `<code>${code.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</code>`;
            } catch (err) {
                document.getElementById('codeView').innerHTML = `<code><!-- Code for ${filePath} will appear here once generated by the agent -->\n\nError: ${err.message}</code>`;
            }
        }

        function setViewMode(mode) {
            viewMode = mode;
            
            const btnPreview = document.getElementById('btnPreview');
            const btnCode = document.getElementById('btnCode');
            const previewFrame = document.getElementById('previewFrame');
            const codeView = document.getElementById('codeView');
            const copyBtn = document.getElementById('copyBtn');

            if (mode === 'preview') {
                btnPreview.classList.add('active');
                btnCode.classList.remove('active');
                previewFrame.style.display = 'block';
                codeView.style.display = 'none';
                copyBtn.style.display = 'none';
            } else {
                btnPreview.classList.remove('active');
                btnCode.classList.add('active');
                previewFrame.style.display = 'none';
                codeView.style.display = 'block';
                copyBtn.style.display = 'block';
            }
        }

        function copyCode() {
            const code = document.getElementById('codeView').innerText;
            navigator.clipboard.writeText(code).then(() => {
                const btn = document.getElementById('copyBtn');
                const originalText = btn.innerText;
                btn.innerText = "Copied!";
                setTimeout(() => btn.innerText = originalText, 2000);
            });
        }

        // Intercept iframe clicks to weave the site naturally
        document.getElementById('previewFrame').onload = function() {
            try {
                const iframeDoc = this.contentDocument || this.contentWindow.document;
                if (!iframeDoc) return;

                iframeDoc.body.addEventListener('click', (e) => {
                    const link = e.target.closest('a');
                    if (!link) return;

                    const href = link.getAttribute('href');
                    if (!href || href.startsWith('http') || href.startsWith('#')) return;

                    // Match href to a dashboard page
                    for (const [key, id] of Object.entries(hrefMap)) {
                        if (href.toLowerCase().includes(key)) {
                            e.preventDefault();
                            loadPage(id);
                            return;
                        }
                    }
                });
            } catch (err) {
                // Cross-origin or empty frame, ignore
            }
        };

